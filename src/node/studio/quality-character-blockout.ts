// Draw a neutral proximity and weight study without input or output sprite pixels.
export function characterBlockoutGuide(w: number, h: number): QualityImage | undefined {
  const masses = volumes[w];
  if (w !== h || !masses) return;
  const side = w;
  const recipe: AssetRecipe = {
    version: 1, name: 'Character construction guide', canvas: { w: side, h: side },
    pivot: { x: side / 2, y: side - 1 }, palette: [0x374454ff, 0x57677aff, 0x798a9dff, 0xa4b2c1ff, 0xd2dce7ff], materials: [],
    frames: [{ id: 'still', durationMs: 100, poses: [] }], loop: false,
    parts: masses.map(([id, color, xy]) => ({
      id, name: id, parentId: null, pivot: { x: 0, y: 0 }, origin: 'authored', materialIds: [],
      paint: [{ kind: 'polygon', color, points: Array.from({ length: xy.length / 2 }, (_, i) => ({ x: xy[i * 2], y: xy[i * 2 + 1] })) }],
    })),
  };
  const blockout = createRecipeRenderer(recipe).renderFrame('still').image;
  return { name: 'construction-volumes.png', data: encodePng(blockout.scale(Math.ceil(192 / side))) };
}
