import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { wireParse } from '../../src/studio/pixel/model.ts';
import { decodeTestPng } from '../../test/fixtures/image-assertions.ts';

test('S3 Chrome: External Engine preview → approval → undo/redo → PNG → reopen → rollback', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.locator('#new-project').click();
  await page.locator('#new-name').fill('S3 · Mock fixture');
  await page.locator('#size-preset').selectOption('32');
  await page.locator('#create-form').getByRole('button', { name: 'Tạo', exact: true }).click();
  await expect(page.locator('#canvas')).toBeVisible();
  const id = await page.locator('#projects').inputValue(), project = `/api/pixel/projects/${id}`;
  const document = async () => wireParse(await (await page.request.get(project)).text());
  const original = await document();
  await page.locator('#ai-open').click();
  await expect(page.locator('#generation-source')).toHaveValue('legacy');
  await expect(page.locator('#ai-generate')).toBeVisible();
  await page.locator('#generation-source').selectOption('external');
  await expect(page.locator('#external-engine-connection')).toContainText('LumaSprite External Mock Engine');
  await expect(page.locator('#ai-generate')).toBeHidden();
  await expect(page.locator('#external-engine-region-label')).toBeHidden();
  await page.locator('#external-engine-kind').selectOption('character');
  await page.locator('#external-engine-brief').fill('Thợ máy pixel 32×32');
  await page.locator('#external-engine-submit').click();
  const preview = page.locator('#external-engine-canvas');
  await expect(preview).toBeVisible();
  await expect(preview).toHaveCSS('width', '32px');
  const pixels = Uint32Array.from(await preview.evaluate((canvas: HTMLCanvasElement) => {
    const rgba = canvas.getContext('2d')!.getImageData(0, 0, canvas.width, canvas.height).data;
    const packed = [];
    for (let i = 0; i < rgba.length; i += 4) packed.push(((rgba[i] << 24) | (rgba[i + 1] << 16) | (rgba[i + 2] << 8) | rgba[i + 3]) >>> 0);
    return packed;
  }));
  expect(pixels.some(ink => ink !== 0)).toBe(true);
  const apply = page.locator('#external-engine-apply');
  await expect(apply).toBeDisabled();
  expect((await document()).revision).toBe(original.revision);
  await page.locator('#external-engine-zoom').selectOption('4');
  await expect(preview).toHaveCSS('width', '128px');
  await expect(preview).toHaveAttribute('width', '32');
  await expect(preview).toHaveCSS('image-rendering', 'pixelated');
  const evidence = process.env.PXL_S3_EVIDENCE_DIR;
  if (evidence) await page.screenshot({ path: join(evidence, 's3-preview.png') });
  await page.locator('#external-engine-approved').check();
  await expect(apply).toBeEnabled();
  await apply.click();
  await expect(page.locator('#generation-workspace')).toBeHidden();
  await expect(page.locator('#asset-info')).toContainText('Mock character');
  await expect.poll(async () => (await document()).assets.length).toBe(2);
  const imported = (await document()).assets[1];
  const libraryEntry = (await document()).studio.library[imported.id];
  const downloaded = page.waitForEvent('download');
  await page.locator('[data-export="png"]').click();
  const download = await downloaded;
  const file = evidence ? join(evidence, 's3-export.png') : (await download.path())!;
  if (evidence) await download.saveAs(file);
  expect(decodeTestPng(await readFile(file)).data).toEqual(pixels);
  if (evidence) await page.screenshot({ path: join(evidence, 's3-editor.png') });
  await page.keyboard.press('Control+z');
  await expect.poll(async () => (await document()).assets.length).toBe(1);
  await page.keyboard.press('Control+Shift+z');
  await expect.poll(async () => (await document()).assets[1]?.id).toBe(imported.id);
  await page.reload();
  await page.locator('#asset-list').getByRole('button', { name: 'Mock character', exact: true }).click();
  await expect(page.locator('#asset-info')).toContainText('Mock character');
  const beforeEdit = (await document()).revision;
  await page.locator('#actual').click();
  await page.locator('#hex').fill('#ff00ffff');
  await page.locator('#hex').press('Tab');
  await page.locator('#canvas').click({ position: { x: 0.5, y: 0.5 } });
  await expect.poll(async () => (await document()).revision).toBeGreaterThan(beforeEdit);
  await page.locator('[data-tool="erase"]').click();
  await page.locator('#canvas').click({ position: { x: 0.5, y: 0.5 } });
  await page.locator('[data-command="layer.add"]').click();
  await page.locator('[data-tool="select"]').click();
  await page.locator('#canvas').click({ position: { x: 1.5, y: 0.5 } });
  await page.locator('[data-tool="pen"]').click();
  await page.locator('#canvas').click({ position: { x: 1.5, y: 0.5 } });
  await page.keyboard.press('Control+z'); await page.keyboard.press('Control+Shift+z');
  await page.locator('header [data-command="file.save"]').click();
  await expect(page.locator('#save-status')).toContainText('Đã lưu');
  await page.reload();
  await page.locator('#asset-list').getByRole('button', { name: 'Mock character', exact: true }).click();
  const edited = page.waitForEvent('download');
  await page.locator('[data-export="png"]').click();
  const editedPixels = decodeTestPng(await readFile((await (await edited).path())!)).data;
  const expected = pixels.slice(); expected[1] = 0xff00ffff;
  expect(editedPixels).toEqual(expected);
  expect((await document()).studio.library[imported.id]).toEqual(libraryEntry);
  await page.locator('#history').click();
  await page.locator('#history-list').getByRole('button', { name: /Trước khi áp dụng External Engine/ }).click();
  await expect.poll(async () => (await document()).assets.length).toBe(1);
  expect(errors).toEqual([]);
});

test('S3 Chrome: rejected and canceled candidates do not modify the project', async ({ page }) => {
  await page.goto('/');
  await page.locator('#new-project').click();
  await page.locator('#new-name').fill('S3 · Job lifecycle');
  await page.locator('#create-form').getByRole('button', { name: 'Tạo', exact: true }).click();
  const project = `/api/pixel/projects/${await page.locator('#projects').inputValue()}`;
  const document = async () => wireParse(await (await page.request.get(project)).text());
  const original = await document();
  await page.locator('#ai-open').click();
  await page.locator('#generation-source').selectOption('external');
  const brief = page.locator('#external-engine-brief'), submit = page.locator('#external-engine-submit');
  await brief.fill('[fixture:slow] Hủy từ Studio');
  await submit.click();
  await page.locator('#external-engine-cancel').click();
  await expect(page.locator('#external-engine-state')).toContainText('Đã hủy');
  await brief.fill('Từ chối từ Studio');
  await submit.click();
  await expect(page.locator('#external-engine-canvas')).toBeVisible();
  await page.locator('#external-engine-reject').click();
  await expect(page.locator('#external-engine-state')).toContainText('Đã từ chối');
  await expect(page.locator('#external-engine-canvas')).toBeHidden();
  expect((await document()).revision).toBe(original.revision);
});
